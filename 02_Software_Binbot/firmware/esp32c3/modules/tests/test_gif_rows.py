"""Run the production GIF decoder on the host and compare pixels to Pillow."""
import os
from pathlib import Path
import subprocess
import sys
import tempfile

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def rgb565(image):
    output = bytearray()
    rgba = image.convert("RGBA")
    background = Image.new("RGBA", image.size, (0, 0, 0, 255))
    image = Image.alpha_composite(background, rgba)
    for red, green, blue in image.convert("RGB").getdata():
        color = ((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3)
        output.extend(color.to_bytes(2, "big"))
    return output


def main():
    with tempfile.TemporaryDirectory(prefix="binbot-gif-rows-") as temporary:
        directory = Path(temporary)
        executable = directory / "test-gif-rows"
        subprocess.run([
            "cc", "-std=c11", "-g", "-O1", "-Wall", "-Wextra",
            "-fsanitize=address,undefined", "-fno-omit-frame-pointer",
            "-I", str(ROOT / "tests/host"),
            "-I", str(ROOT / "components/service_gif/include"),
            "-I", str(ROOT / "components/service_storage/include"),
            str(ROOT / "components/service_gif/gif_player.c"),
            str(ROOT / "tests/host/test_gif_rows.c"), "-o", str(executable),
        ], check=True)
        cases = []
        for width, height in ((132, 132), (240, 240), (320, 240), (317, 239)):
            frames = []
            for frame in range(3):
                image = Image.new("P", (width, height))
                palette = [value for index in range(256)
                           for value in ((index * 3 + frame * 61) % 256,
                                         (index * 7 + frame * 97) % 256,
                                         (index * 11 + frame * 31) % 256)]
                image.putpalette(palette)
                image.putdata([(x + y * 17 + frame * 43) % 256
                               for y in range(height) for x in range(width)])
                frames.append(image)
            source = directory / f"{width}x{height}.gif"
            frames[0].save(source, save_all=True, append_images=frames[1:],
                           duration=[80, 120, 160], loop=0, optimize=False,
                           disposal=2, interlace=False)
            cases.append(source)
        for transparent_index in (0, 255):
            transparent = directory / f"transparent-{transparent_index}.gif"
            frames[0].save(transparent, transparency=transparent_index,
                           optimize=False, interlace=False)
            cases.append(transparent)
        # Also verify exactly the format generated by the web upload pipeline.
        normalized = directory / "normalized.gif"
        subprocess.run([
            "ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(cases[2]),
            "-filter_complex", "fps=12.5,format=rgba,split[s0][s1];"
            "[s0]palettegen=max_colors=256:reserve_transparent=1[p];"
            "[s1][p]paletteuse=dither=sierra2_4a:alpha_threshold=128",
            "-gifflags", "-offsetting-transdiff", str(normalized),
        ], check=True)
        cases.append(normalized)
        for width, height in ((240, 240), (320, 240)):
            moving = []
            for index in range(3):
                image = Image.new("P", (width, height), 0)
                image.putpalette([177, 155, 149, 240, 32, 48, 32, 240, 64] + [0] * 759)
                for y in range(40, height - 40):
                    for x in range(20 + index * 70, 60 + index * 70):
                        image.putpixel((x, y), 1 + index % 2)
                moving.append(image)
            source = directory / f"moving-{width}.gif"
            moving[0].save(source, save_all=True, append_images=moving[1:],
                           duration=80, loop=0, transparency=0, disposal=2,
                           optimize=False, interlace=False)
            normalized = directory / f"normalized-transparent-{width}.gif"
            subprocess.run([
                "ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(source),
                "-filter_complex", "fps=12.5,format=rgba,split[s0][s1];"
                "[s0]palettegen=max_colors=256:reserve_transparent=1[p];"
                "[s1][p]paletteuse=dither=sierra2_4a:alpha_threshold=128",
                "-gifflags", "-offsetting-transdiff", str(normalized),
            ], check=True)
            with Image.open(normalized) as image:
                for index in range(image.n_frames):
                    image.seek(index)
                    assert image.convert("RGBA").getpixel((0, 0))[3] == 0
            cases.append(normalized)
        cases.extend(Path(path) for path in sys.argv[1:])
        environment = {**os.environ, "ASAN_OPTIONS": "detect_leaks=1"}
        for source in cases:
            with Image.open(source) as image:
                reference = bytearray()
                for frame in range(image.n_frames):
                    image.seek(frame)
                    reference.extend(rgb565(image))
                count = image.n_frames
            output = directory / f"{source.stem}.rgb565"
            subprocess.run([str(executable), str(source), str(output), str(count)],
                           check=True, env=environment)
            actual = output.read_bytes()
            assert actual == reference * 2, f"incorrect decoded pixels: {source.name}"
            print(f"{source.name}: {count} frames, rows/loop/pixels/bounds passed")


if __name__ == "__main__":
    main()
